// Bundle the ACP agent server into one file the app can ship (#14).
//
// An external editor integrates with an ACP agent by SPAWNING it (stdio is the
// only transport v1 stabilizes), so "Open Science as an ACP agent" has to be a
// command on disk. This produces that command: a single ESM file with the SDK
// inlined, written into `runtime/acp-server/` where Tauri picks it up as a
// bundled resource — no npm install for the user, nothing to publish.
//
// Node-only output on purpose: it is spawned by an editor, never loaded by the
// webview.
import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "runtime/acp-server");
const entry = resolve(outDir, "entry.mjs");

await mkdir(outDir, { recursive: true });
// The entry is generated rather than checked in: it is two lines, and keeping
// it beside the bundle makes it obvious that everything here is build output.
await writeFile(
  entry,
  [
    "// Generated by scripts/build-acp-server.mjs — do not edit.",
    'import { main } from "@ai4s/sdk/acp/serve-stdio";',
    "await main();",
    "",
  ].join("\n"),
);

await build({
  entryPoints: [entry],
  outfile: resolve(outDir, "acp-server.mjs"),
  bundle: true,
  platform: "node",
  target: "node18",
  format: "esm",
  // Resolve the workspace package the same way the app's Vite config does.
  alias: {
    "@ai4s/sdk/acp/serve-stdio": resolve(root, "packages/sdk/src/acp/serve-stdio.ts"),
    "@ai4s/sdk/acp": resolve(root, "packages/sdk/src/acp/index.ts"),
    "@ai4s/sdk": resolve(root, "packages/sdk/src/index.ts"),
    "@ai4s/shared": resolve(root, "packages/shared/src/index.ts"),
  },
  banner: {
    // An editor spawning this must see ACP messages on stdout and nothing else,
    // so any accidental console.log is redirected to stderr up front.
    js: "console.log = console.error;",
  },
  logLevel: "warning",
});

process.stdout.write(`acp-server bundled → ${resolve(outDir, "acp-server.mjs")}\n`);
